export function getCollection(id: string): CollectionRecord | undefined {
  return COLLECTIONS.find((collection) => collection.id === id);
}

export function getProduct(slug: string): ProductRecord | undefined {
  return PRODUCTS.find((product) => product.slug === slug);
}

export function productsByCollection(id: CollectionId): ProductRecord[] {
  return PRODUCTS.filter((product) => product.collection === id);
}

export function collectionName(id: CollectionId): string {
  return getCollection(id)?.name ?? id;
}

export function categoryName(id: CategoryId): string {
  return CATEGORIES.find((category) => category.id === id)?.name ?? id;
}

export function relatedProducts(product: ProductRecord, limit = 4): ProductRecord[] {
  return PRODUCTS.filter(
    (candidate) =>
      candidate.sku !== product.sku && candidate.collection === product.collection,
  ).slice(0, limit);
}

export function searchProducts(query: string, products = PRODUCTS): ProductRecord[] {
  const term = query.trim().toLowerCase();
  if (!term) return products;
  return products.filter((product) =>
    [product.sku, product.name, collectionName(product.collection), categoryName(product.category), product.color, product.finish]
      .join(" ")
      .toLowerCase()
      .includes(term),
  );
}
